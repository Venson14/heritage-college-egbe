  document.addEventListener("DOMContentLoaded", function () {
    const observerOptions = {
      root: null,
      threshold: 0.15
    };

    const revealCallback = (entries, observer) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('active');
          observer.unobserve(entry.target);
        }
      });
    };

    const observer = new IntersectionObserver(revealCallback, observerOptions);
    const targets = document.querySelectorAll('.reveal-fade-up, .reveal-slide-left');
    targets.forEach(target => observer.observe(target));

    const statItems = document.querySelectorAll('.stat-item h3[data-target]');

    const animateStat = (element) => {
      const target = Number(element.dataset.target || 0);
      const suffix = element.dataset.suffix || '';
      const duration = 1400;
      const startTime = performance.now();

      function updateCounter(currentTime) {
        const elapsed = currentTime - startTime;
        const progress = Math.min(elapsed / duration, 1);
        const eased = 1 - Math.pow(1 - progress, 3);
        const value = Math.round(target * eased);
        element.textContent = value + suffix;

        if (progress < 1) {
          requestAnimationFrame(updateCounter);
        } else {
          element.textContent = target + suffix;
        }
      }

      requestAnimationFrame(updateCounter);
    };

    const statObserver = new IntersectionObserver((entries, statObserverInstance) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          animateStat(entry.target);
          statObserverInstance.unobserve(entry.target);
        }
      });
    }, { threshold: 0.4 });

    statItems.forEach(item => statObserver.observe(item));
  });

